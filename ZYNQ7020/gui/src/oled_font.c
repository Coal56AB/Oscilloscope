static const uint8_t GlyphColon[5]   = {0x00U, 0x36U, 0x36U, 0x00U, 0x00U};
static const uint8_t GlyphPercent[5] = {0x63U, 0x13U, 0x08U, 0x64U, 0x63U};
static const uint8_t GlyphDash[5]    = {0x08U, 0x08U, 0x08U, 0x08U, 0x08U};
static const uint8_t GlyphDot[5]     = {0x00U, 0x60U, 0x60U, 0x00U, 0x00U};
static const uint8_t GlyphSlash[5]   = {0x20U, 0x10U, 0x08U, 0x04U, 0x02U};

const uint8_t *Font5x7_GetGlyph(char symbol)
{
  if(symbol >= '0' && symbol <= '9')
    return FontDigits[(unsigned)(symbol - '0')];
  if(symbol >= 'a' && symbol <= 'z')
    symbol = (char)(symbol - 'a' + 'A');
  if(symbol >= 'A' && symbol <= 'Z')
    return FontLetters[(unsigned)(symbol - 'A')];

  switch(symbol)
  {
    case ':': return GlyphColon;
    case '%': return GlyphPercent;
    case '-': return GlyphDash;
    case '.': return GlyphDot;
    case '/': return GlyphSlash;
    default: return NULL;
  }
}
